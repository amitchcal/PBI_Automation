// Copies the brand kit output (tokens, logos) into the web app. Run after changing the kit:  npm run sync-brand -- meridian
import fs from "node:fs";
import path from "node:path";
const kit = process.argv[2] || "meridian";
const src = path.resolve(process.cwd(), "..", "kit", "brand", "out", kit);
const tokens = fs.readFileSync(path.join(src, "web", "tokens.css"), "utf8");
const body = tokens.match(/:root\s*\{([\s\S]*?)\}/)[1];
fs.writeFileSync(path.resolve("src/app/brand.css"), `/* Generated by scripts/sync-brand.mjs from the brand kit "${kit}". Do not edit by hand. */\n@theme {\n${body}}\n`);
fs.mkdirSync(path.resolve("public/brand"), { recursive: true });
for (const f of ["logo-mark.png", "logo-full.png", "logo-full-light.png", "logo-mark.svg"]) fs.copyFileSync(path.join(src, f), path.resolve("public/brand", f));
console.log("brand synced from", kit);
